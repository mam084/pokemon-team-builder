"""
damage.py

Damage calculator for Pokemon Champions (level 50, Gen 9 damage formula).

It follows Pokemon Showdown's order of operations and integer rounding
exactly - every modifier is a fraction of 4096, chained the way the game
chains them - and tests/test_damage.py checks it roll-for-roll against
Showdown's own engine (vectors generated by scripts/make_damage_vectors.js).

    base   = floor(floor(floor(22 * BP * Atk) / Def) / 50) + 2
    damage = base -> spread -> weather -> crit -> random (85-100%)
                  -> STAB -> type -> final modifiers (screens, Life Orb...)

Modeled: stat stages, crits, spread moves, sun/rain/sand/snow (and Mega Sol),
Electric/Grassy/Psychic/Misty Terrain, Helping Hand, Reflect / Light Screen /
Aurora Veil, the common damage-relevant abilities and items (see the tables
below), Body Press, Foul Play, Psyshock, Weather Ball, Knock Off,
multi-hit moves and -ate abilities.

Not modeled (results are flagged where it matters): moves whose power depends
on battle history (Last Respects, Rage Fist...), and abilities or items not
listed below.
"""

from __future__ import annotations

from dataclasses import dataclass, field
