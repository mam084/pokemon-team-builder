# --- inputs -------------------------------------------------------------------


@dataclass
class Battler:
    form: Species
    stats: dict
    ability: str = ""            # id
    item: str = ""               # id
    boosts: dict = field(default_factory=dict)
    full_hp: bool = True

    @property
    def types(self) -> list[str]:
        return list(self.form.types)

    @property
    def grounded(self) -> bool:
        return "Flying" not in self.form.types and self.ability != "levitate"

    @classmethod
    def from_set(cls, pset: PokemonSet, dex: Dex, boosts: dict | None = None) -> "Battler":
        form = pset.battle_form(dex)
        return cls(
            form=form,
            stats=calc_stats(form.base_stats, pset.sps, dex.get_nature(pset.nature)),
            ability=to_id(pset.battle_ability(dex)),
            item=to_id(pset.item),
            boosts=dict(boosts or {}),
        )


@dataclass
class Field:
    doubles: bool = True
    spread: bool | None = None      # None: decide from the move's target (doubles only)
    weather: str | None = None      # "sun", "rain", "sand", "snow"
    terrain: str | None = None      # "electric", "grassy", "psychic", "misty"
    helping_hand: bool = False
    screen: bool = False            # Reflect vs physical / Light Screen vs special on the defender's side
    aurora_veil: bool = False
    crit: bool = False


@dataclass
class DamageResult:
    rolls: list[int]                # 16 damage rolls, lowest first (total over all hits)
    defender_hp: int
    hits: int = 1
    notes: list[str] = field(default_factory=list)

    @property
    def min(self) -> int:
        return self.rolls[0] if self.rolls else 0

    @property
    def max(self) -> int:
        return self.rolls[-1] if self.rolls else 0

    @property
    def min_pct(self) -> float:
        return 100 * self.min / self.defender_hp

    @property
    def max_pct(self) -> float:
        return 100 * self.max / self.defender_hp

    def ko_chance(self, n: int) -> float:
        """Chance n uses of the move KO from full HP (ignores recovery and chip)."""
        if not self.max:
            return 0.0
        if self.min * n >= self.defender_hp:
            return 1.0
        if self.max * n < self.defender_hp:
            return 0.0
        hits = sum(1 for combo in product(self.rolls, repeat=n) if sum(combo) >= self.defender_hp)
        return hits / len(self.rolls) ** n

    @property
    def verdict(self) -> str:
        if not self.max:
            return "No damage"
        for n in range(1, 5):
            p = self.ko_chance(n)
            label = "OHKO" if n == 1 else f"{n}HKO"
            if p >= 1:
                return f"Guaranteed {label}"
            if p > 0:
                return f"{p:.1%} chance to {label}"
        return f"{-(-self.defender_hp // max(self.max, 1))}+ hits to KO"

    @property
    def summary(self) -> str:
        return f"{self.min}-{self.max} ({self.min_pct:.1f}-{self.max_pct:.1f}%) · {self.verdict}"


# --- the calculation ------------------------------------------------------------


def _move_type_and_power(move: dict, att: Battler, f: Field) -> tuple[str, int, list[int], bool]:
    mtype, bp, bp_mods, ate = move["type"], move["basePower"] or 0, [], False
    weather = "sun" if att.ability == "megasol" else f.weather
    if move["id"] == "weatherball" and weather:
        mtype = {"sun": "Fire", "rain": "Water", "sand": "Rock", "snow": "Ice"}[weather]
        bp = 100
    if att.ability in ATE_ABILITIES and mtype == "Normal" and move["id"] not in NO_ATE:
        mtype, ate = ATE_ABILITIES[att.ability], True
    return mtype, bp, bp_mods, ate


def calculate(att: Battler, dfn: Battler, move: dict, f: Field | None = None) -> DamageResult:
    f = f or Field()
    hp = dfn.stats["hp"]
    notes: list[str] = []
    if move["category"] == "Status" or not move.get("basePower"):
        return DamageResult([0] * 16, hp, notes=["Status move or fixed-damage move"])

    physical = move["category"] == "Physical"
    mtype, bp, _, ate = _move_type_and_power(move, att, f)
    contact = "contact" in move.get("flags", [])
    weather = f.weather
    att_weather = "sun" if att.ability == "megasol" else weather

    # Immunities (type chart first, then abilities)
    effectiveness = defensive_multiplier([t.lower() for t in dfn.types], mtype.lower())
    if effectiveness == 0 or IMMUNITY_ABILITIES.get(dfn.ability) == mtype:
        return DamageResult([0] * 16, hp, notes=["Immune"])
    if mtype == "Ground" and not dfn.grounded:
        return DamageResult([0] * 16, hp, notes=["Immune (not grounded)"])

    # Knock Off / Acrobatics adjust base power directly
    if move["id"] == "acrobatics" and not att.item:
        bp *= 2

    # BasePower modifiers
    bp_mods: list[int] = []
    if att.ability == "technician" and bp <= 60:
        bp_mods.append(6144)
    if ate:
        bp_mods.append(4915)
    if att.ability == "toughclaws" and contact:
        bp_mods.append(5325)
    if att.ability == "ironfist" and "punch" in move["flags"]:
        bp_mods.append(4915)
    if att.ability == "strongjaw" and "bite" in move["flags"]:
        bp_mods.append(6144)
    if att.ability == "megalauncher" and "pulse" in move["flags"]:
        bp_mods.append(6144)
    if att.ability == "sharpness" and "slicing" in move["flags"]:
        bp_mods.append(6144)
    if att.ability == "sheerforce" and move.get("hasSecondary"):
        bp_mods.append(5325)
    if att.ability == "reckless" and move.get("recoil"):
        bp_mods.append(4915)
    if TYPE_ITEMS.get(att.item) == mtype:
        bp_mods.append(4915)
    if att.item == "muscleband" and physical:
        bp_mods.append(4505)
    if att.item == "wiseglasses" and not physical:
        bp_mods.append(4505)
    if att.item == "punchingglove" and "punch" in move["flags"]:
        bp_mods.append(4506)
    if move["id"] == "knockoff" and dfn.item and not dfn.form.is_mega:  # a Mega's stone can't be removed
        bp_mods.append(6144)
    if f.helping_hand:
        bp_mods.append(6144)
    terrain = f.terrain
    if terrain and att.grounded and TERRAIN_TYPES.get(f"{terrain}terrain") == mtype:
        bp_mods.append(5325)
    if terrain == "psychic" and move["id"] == "expandingforce" and att.grounded:
        bp_mods.append(6144)
    if terrain == "grassy" and move["id"] in {"earthquake", "bulldoze"} and dfn.grounded:
        bp_mods.append(2048)
    if terrain == "misty" and mtype == "Dragon" and dfn.grounded:
        bp_mods.append(2048)
    if dfn.ability == "dryskin" and mtype == "Fire":
        bp_mods.append(5120)
    bp = max(1, apply(bp, bp_mods))

    # Attack / Defense stats
    off_stat = move.get("offensiveStat") or ("atk" if physical else "spa")
    def_stat = move.get("defensiveStat") or ("def" if physical else "spd")
    source = dfn if move.get("usesTargetAttack") else att
    atk_stage = source.boosts.get(off_stat, 0)
    def_stage = dfn.boosts.get(def_stat, 0)
    if f.crit or move.get("alwaysCrits"):
        atk_stage = max(atk_stage, 0)
        def_stage = min(def_stage, 0)
    attack = boosted(source.stats[off_stat], atk_stage)
    defense = boosted(dfn.stats[def_stat], def_stage)

    atk_mods: list[int] = []
    if physical:
        if att.ability in {"hugepower", "purepower"}:
            atk_mods.append(8192)
        if att.ability in {"hustle", "gorillatactics"}:
            atk_mods.append(6144)
        if att.item == "choiceband":
            atk_mods.append(6144)
    else:
        if att.ability == "solarpower" and att_weather == "sun":
            atk_mods.append(6144)
        if att.item == "choicespecs":
            atk_mods.append(6144)
    if att.ability == "steelworker" and mtype == "Steel":
        atk_mods.append(6144)
    if att.ability == "transistor" and mtype == "Electric":
        atk_mods.append(5325)
    if att.ability == "dragonsmaw" and mtype == "Dragon":
        atk_mods.append(6144)
    if att.ability == "waterbubble" and mtype == "Water":
        atk_mods.append(8192)
    if dfn.ability == "thickfat" and mtype in {"Fire", "Ice"}:
        atk_mods.append(2048)
    if dfn.ability in {"heatproof", "waterbubble"} and mtype == "Fire":
        atk_mods.append(2048)
    if dfn.ability == "purifyingsalt" and mtype == "Ghost":
        atk_mods.append(2048)
    attack = apply(attack, atk_mods)

    def_mods: list[int] = []
    if def_stat == "spd":
        if weather == "sand" and "Rock" in dfn.types:
            def_mods.append(6144)
        if dfn.item == "assaultvest":
            def_mods.append(6144)
    else:
        if weather == "snow" and "Ice" in dfn.types:
            def_mods.append(6144)
        if dfn.ability == "furcoat":
            def_mods.append(8192)
        if dfn.ability == "grasspelt" and terrain == "grassy":
            def_mods.append(6144)
    defense = apply(defense, def_mods)

    base = tr(tr(tr(22 * bp * attack) / defense) / 50) + 2

    # Modifiers before the random roll
    spread = f.spread if f.spread is not None else (f.doubles and move.get("spread", False))
    if spread and f.doubles:
        base = modify(base, 3072)
    if att_weather == "sun" and mtype in {"Fire", "Water"}:
        base = modify(base, 6144 if mtype == "Fire" else 2048)
    elif weather == "rain" and mtype in {"Fire", "Water"}:
        base = modify(base, 6144 if mtype == "Water" else 2048)
    crit = f.crit or move.get("alwaysCrits", False)
    if crit:
        base = tr(base * 1.5)

    stab = 6144 if mtype in att.types else 4096
    if stab == 6144 and att.ability == "adaptability":
        stab = 8192

    final_mods: list[int] = []
    if f.screen or f.aurora_veil:
        if not crit:
            final_mods.append(2732 if f.doubles else 2048)
    if dfn.full_hp and dfn.ability in {"multiscale", "shadowshield"}:
        final_mods.append(2048)
    if effectiveness > 1 and dfn.ability in {"filter", "solidrock", "prismarmor"}:
        final_mods.append(3072)
    if dfn.ability == "fluffy":
        if contact and mtype != "Fire":
            final_mods.append(2048)
        elif mtype == "Fire" and not contact:
            final_mods.append(8192)
    if dfn.ability == "icescales" and not physical:
        final_mods.append(2048)
    if dfn.ability == "punkrock" and "sound" in move["flags"]:
        final_mods.append(2048)
    if dfn.ability == "auraguard" and contact:
        final_mods.append(2048)
    if att.ability == "tintedlens" and effectiveness < 1:
        final_mods.append(8192)
    if att.ability == "sniper" and crit:
        final_mods.append(6144)
    if att.item == "expertbelt" and effectiveness > 1:
        final_mods.append(4915)
    if att.item == "lifeorb":
        final_mods.append(5324)
    berry = RESIST_BERRIES.get(dfn.item)
    if (berry == mtype and effectiveness > 1) or (dfn.item == "chilanberry" and mtype == "Normal"):
        final_mods.append(2048)
        notes.append(f"{dfn.item} halves the first hit")

    rolls = []
    for r in range(16):
        dmg = tr(tr(base * (100 - r)) / 100)
        dmg = modify(dmg, stab) if stab != 4096 else dmg
        if effectiveness >= 2:
            dmg *= int(effectiveness)
        elif 0 < effectiveness < 1:
            for _ in range(int(round(1 / effectiveness)).bit_length() - 1):
                dmg = tr(dmg / 2)
        dmg = apply(dmg, final_mods)
        rolls.append(max(1, dmg) & 0xFFFF)
    rolls.sort()

    hits = 1
    multihit = move.get("multihit")
    if isinstance(multihit, int) and multihit > 1:
        hits = multihit
        rolls = [r * hits for r in rolls]
        notes.append(f"{hits} hits, each rolled the same (estimate)")
    elif isinstance(multihit, list):
        notes.append(f"hits {multihit[0]}-{multihit[1]} times; shown per hit")
    if move.get("variablePower"):
        notes.append("power changes during battle; shown at base power")
    return DamageResult(rolls, hp, hits, notes)


def calc_sets(attacker: PokemonSet, defender: PokemonSet, move_name: str, dex: Dex,
              field: Field | None = None, att_boosts: dict | None = None,
              def_boosts: dict | None = None) -> DamageResult:
    """Convenience wrapper taking two PokemonSets and a move name."""
    move = dex.get_move(move_name)
    if move is None:
        raise KeyError(move_name)
    return calculate(Battler.from_set(attacker, dex, att_boosts), Battler.from_set(defender, dex, def_boosts),
                     move, field)
