# --- integer helpers matching Showdown ------------------------------------


def tr(x: float) -> int:
    return int(x) if x >= 0 else -int(-x)


def modify(value: int, mod: int) -> int:
    """value * mod/4096, Showdown rounding (round half down)."""
    return tr((tr(value * mod) + 2048 - 1) / 4096)


def chain(mods: list[int]) -> int:
    total = 4096
    for m in mods:
        total = (total * m + 2048) >> 12
    return total


def apply(value: int, mods: list[int]) -> int:
    return modify(value, chain(mods)) if mods else value


BOOST_TABLE = [1, 1.5, 2, 2.5, 3, 3.5, 4]


def boosted(stat: int, stage: int) -> int:
    stage = max(-6, min(6, stage))
    if stage >= 0:
        return int(stat * BOOST_TABLE[stage])
    return int(stat / BOOST_TABLE[-stage])


