"""
Damage calculator tests.

tests/fixtures/damage_vectors.json holds all 16 damage rolls that Pokemon
Showdown's own engine produces for ~100 attacker / defender / move / field
combinations (generated by scripts/make_damage_vectors.js). src/damage.py must
reproduce every roll exactly.
"""

import json
import unittest
from pathlib import Path

from src.damage import Battler, Field, calculate
from src.dex import STATS, load_dex, to_id
from src.stats import calc_stats

VECTORS = json.loads((Path(__file__).resolve().parent / "fixtures" / "damage_vectors.json").read_text())


def battler(spec, dex, boosts):
    species, item, ability, nature, sps = spec
    form = dex.get_species(species)
    sps = {s: sps.get(s, 0) for s in STATS}
    return Battler(form=form, stats=calc_stats(form.base_stats, sps, dex.get_nature(nature)),
                   ability=to_id(ability), item=to_id(item), boosts=boosts)


class TestDamageAgainstShowdown(unittest.TestCase):
    def test_vectors(self):
        dex = load_dex("regmc")
        mismatches = []
        for v in VECTORS:
            att = battler(v["attacker"], dex, v["att_boosts"])
            dfn = battler(v["defender"], dex, v["def_boosts"])
            f = v["field"]
            field = Field(doubles=v["doubles"], spread=f["spread"], weather=f["weather"], terrain=f["terrain"],
                          helping_hand=f["helping_hand"], screen=f["screen"], crit=f["crit"])
            result = calculate(att, dfn, dex.get_move(v["move"]), field)
            self.assertEqual(dfn.stats["hp"], v["hp"], v["defender"][0])
            if result.rolls != v["rolls"]:
                mismatches.append(f"{v['attacker'][0]} {v['move']} -> {v['defender'][0]} "
                                  f"{'dbl' if v['doubles'] else 'sgl'} {f}: got {result.rolls[:3]}..{result.rolls[-1]} "
                                  f"want {v['rolls'][:3]}..{v['rolls'][-1]}")
        self.assertFalse(mismatches, "\n" + "\n".join(mismatches))

    def test_ko_text(self):
        dex = load_dex("regmc")
        v = next(x for x in VECTORS if x["move"] == "Close Combat" and x["defender"][0] == "Kingambit")
        result = calculate(battler(v["attacker"], dex, {}), battler(v["defender"], dex, {}), dex.get_move(v["move"]),
                           Field(doubles=v["doubles"]))
        self.assertIn("OHKO", result.verdict)


if __name__ == "__main__":
    unittest.main()
